import type { Metadata } from "next";
import { IBM_Plex_Sans, IBM_Plex_Mono, Noto_Sans_TC } from "next/font/google";
import "./globals.css";
import Navbar from '../components/Navbar';
import Footer from '../components/Footer';
import MyQueryClientProvider from "../providers/MyQueryClientProvider";
import { LocaleProvider } from "@/src/i18n/LocaleContext";

const plexSans = IBM_Plex_Sans({
  weight: ["400", "500", "600"],
  subsets: ["latin"],
  variable: "--font-plex-sans",
});

const plexMono = IBM_Plex_Mono({
  weight: ["400", "500"],
  subsets: ["latin"],
  variable: "--font-plex-mono",
});

// There is no `chinese-traditional` subset exposed by next/font; the CJK
// glyphs still load from the full font file, this subset only controls
// which Latin-range glyphs are preloaded.
const notoTC = Noto_Sans_TC({
  weight: ["400", "500"],
  subsets: ["latin"],
  variable: "--font-noto-tc",
});

export const metadata: Metadata = {
  title: "Metabolomics Analysis Assistant",
  description: "Generated by create next app",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="zh-Hant">
      {/*
        No dark-mode workaround needed here: this design has no dark mode.
        The previous variant
        class on <body>, which switched body text to a lighter tone under
        the OS-level prefers-color-scheme media query, is gone along with
        the rest of that theme.
      */}
      <body
        className={`${plexSans.variable} ${plexMono.variable} ${notoTC.variable} antialiased`}
      >
        <LocaleProvider>
          <Navbar />
          <main>
            <MyQueryClientProvider>
              {children}
            </MyQueryClientProvider>
          </main>
          <Footer />
        </LocaleProvider>
      </body>
    </html>
  );
}
